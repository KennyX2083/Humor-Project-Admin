import { writeFile } from "node:fs/promises";

async function getJson(url) {
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(`Request failed: ${response.status} ${url}`);
  }

  return response.json();
}

function sortedNames(names) {
  if (
    !names.length ||
    names.some((name) => typeof name !== "string" || !name.trim())
  ) {
    throw new Error("A roster returned empty or invalid names.");
  }

  return [...new Set(names)].sort((a, b) => a.localeCompare(b, "en"));
}

async function main() {
  const versions = await getJson(
    "https://ddragon.leagueoflegends.com/api/versions.json"
  );

  const [valorant, league, overwatch] = await Promise.all([
    getJson(
      "https://valorant-api.com/v1/agents?isPlayableCharacter=true&language=en-US"
    ),
    getJson(
      `https://ddragon.leagueoflegends.com/cdn/${versions[0]}/data/en_US/champion.json`
    ),
    getJson("https://overfast-api.tekrop.fr/heroes"),
  ]);

  const rosters = {
    valorant: sortedNames(
      valorant.data
        .filter((agent) => agent.isPlayableCharacter)
        .map((agent) => agent.displayName)
    ),
    league: sortedNames(
      Object.values(league.data).map((champion) => champion.name)
    ),
    overwatch: sortedNames(overwatch.map((hero) => hero.name)),
  };

  const content =
    "// Generated by scripts/update-rosters.mjs. Do not edit manually.\n" +
    "export const gameCharacters: Record<string, string[]> = " +
    JSON.stringify(rosters, null, 2) +
    ";\n";

  await writeFile(
    new URL("../lib/game-characters.ts", import.meta.url),
    content,
    "utf8"
  );

  for (const [game, names] of Object.entries(rosters)) {
    console.log(`${game}: ${names.length} characters`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});