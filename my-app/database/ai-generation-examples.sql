create table public.ai_generation_examples (
 id bigint generated by default as identity primary key,
 title text not null check (char_length(btrim(title)) between 1 and 100),
 game text not null check (game in ('valorant','league','overwatch')),
 character_name text check (character_name is null or char_length(character_name) <= 100),
 situation text not null check (char_length(btrim(situation)) between 5 and 1000),
 example_excuse text not null check (char_length(btrim(example_excuse)) between 1 and 4000),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index ai_generation_examples_game_id_idx on public.ai_generation_examples(game,id desc);
alter table public.ai_generation_examples enable row level security;
revoke all on public.ai_generation_examples from anon, authenticated;
grant select,insert,update,delete on public.ai_generation_examples to authenticated;
create policy "Admins manage generation examples" on public.ai_generation_examples
 for all to authenticated using ((select private.is_superadmin()))
 with check ((select private.is_superadmin()));
