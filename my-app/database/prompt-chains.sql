create table public.prompt_chains (
 id bigint generated by default as identity primary key,
 slug text not null unique check (char_length(slug) between 1 and 100),
 name text not null check (char_length(name) between 1 and 100),
 description text not null default '',
 created_at timestamptz not null default now()
);
create table public.prompt_chain_steps (
 id bigint generated by default as identity primary key,
 chain_id bigint not null references public.prompt_chains(id) on delete restrict,
 position integer not null check (position between 1 and 10),
 name text not null check (char_length(name) between 1 and 100),
 instructions text not null check (char_length(instructions) between 1 and 8000),
 created_at timestamptz not null default now(),
 unique(chain_id, position),
 unique(id, chain_id)
);
alter table public.generation_request add column chain_id bigint references public.prompt_chains(id) on delete restrict;
alter table public.llm_response
 add column step_id bigint,
 add column chain_id bigint,
 add constraint llm_response_step_chain_fk foreign key(step_id, chain_id) references public.prompt_chain_steps(id, chain_id) on delete restrict,
 add constraint llm_response_step_chain_pair check ((step_id is null) = (chain_id is null));
create index generation_request_chain_id_idx on public.generation_request(chain_id);
create index llm_response_step_chain_idx on public.llm_response(step_id, chain_id);
alter table public.prompt_chains enable row level security;
alter table public.prompt_chain_steps enable row level security;
revoke all on public.prompt_chains, public.prompt_chain_steps from anon, authenticated;
grant select on public.prompt_chains, public.prompt_chain_steps to authenticated;
create policy "Admins read prompt chains" on public.prompt_chains for select to authenticated using ((select private.is_superadmin()));
create policy "Admins read prompt chain steps" on public.prompt_chain_steps for select to authenticated using ((select private.is_superadmin()));
