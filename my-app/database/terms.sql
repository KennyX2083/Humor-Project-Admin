create table public.terms (
 id bigint generated by default as identity primary key,
 term text not null check (char_length(btrim(term)) between 1 and 100),
 definition text not null check (char_length(btrim(definition)) between 1 and 2000),
 example text check (example is null or char_length(example) <= 2000),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create unique index terms_normalized_term_key on public.terms(lower(btrim(term)));
alter table public.terms enable row level security;
revoke all on public.terms from anon, authenticated;
grant select, insert, update, delete on public.terms to authenticated;
create policy "Admins manage terms" on public.terms
 for all to authenticated
 using ((select private.is_superadmin()))
 with check ((select private.is_superadmin()));
