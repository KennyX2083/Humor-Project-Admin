create table public.allowed_signup_domains (
 id bigint generated by default as identity primary key,
 domain text not null unique check (
 char_length(domain) between 3 and 253 and domain=lower(btrim(domain))
 and domain !~ '[[:space:]/@:]' and position('.' in domain)>0),
 notes text check (notes is null or char_length(notes)<=500),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table public.whitelist_email_addresses (
 id bigint generated by default as identity primary key,
 email_address text not null unique check (
 char_length(email_address) between 3 and 254 and email_address=lower(btrim(email_address))
 and email_address ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
 notes text check (notes is null or char_length(notes)<=500),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
alter table public.allowed_signup_domains enable row level security;
alter table public.whitelist_email_addresses enable row level security;
revoke all on public.allowed_signup_domains,public.whitelist_email_addresses from anon,authenticated;
grant select,insert,update,delete on public.allowed_signup_domains,public.whitelist_email_addresses to authenticated;
create policy "Admins manage signup domains" on public.allowed_signup_domains
 for all to authenticated using ((select private.is_superadmin())) with check ((select private.is_superadmin()));
create policy "Admins manage whitelisted emails" on public.whitelist_email_addresses
 for all to authenticated using ((select private.is_superadmin())) with check ((select private.is_superadmin()));
